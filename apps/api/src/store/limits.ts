  (RUN_SUBREQUEST_BUDGET -
    INDEX_READ_COST -
    DISCOVERY_COST -
    PERSIST_COST -
    SHARED_LOOKUP_COST -
    MAX_ADDRESSES_PER_RUN * VISIT_COST) /
    REGISTRATION_COST
